//! The brain of `docs/CAPABILITIES.md`: a pure function from what each preset resolves to (its
//! definition, the capabilities its adapter reports, and the rows of its catalog file) to the
//! page. It reads no file and starts no provider, so the page can only say what the code says;
//! `tests/capability_matrix.rs` builds the rows from the real adapters and fails when the
//! committed page is not what this returns.

use aibus_provider::presets::ProviderDef;
use aibus_provider::{Api, Capabilities, CompatFlag};
use serde_json::Value;

/// One preset as the matrix sees it. The fields vary together per preset.
pub struct Row {
    pub def: ProviderDef,
    /// What the adapter reports for a model of this provider that its table says nothing about.
    pub caps: Capabilities,
    /// The rows of the preset's catalog file.
    pub catalog_rows: usize,
}

/// The config `auth` forms a preset accepts. A key-based preset takes a keychain entry, an
/// environment variable or a `0600` file; a local server takes none; the two cloud presets take
/// their own forms.
fn auth_kinds(def: &ProviderDef) -> Vec<&'static str> {
    match def.api {
        Some(Api::AnthropicBedrock) => vec!["sigv4", "aws_env", "aws_profile", "env"],
        Some(Api::AnthropicVertex) => vec!["gcloud"],
        _ => {
            let has = |m: &str| def.auth_methods.iter().any(|a| a == m);
            let mut kinds = Vec::new();
            if has("api_key") || has("bearer") || has("env") {
                kinds.extend(["keyring", "env", "file"]);
            }
            if has("none") {
                kinds.push("none");
            }
            kinds
        }
    }
}

/// Whether the adapter can ask the server for its model list, and whether it can count tokens
/// before a request. Bedrock and Vertex have neither endpoint here, the OpenAI wires have no
/// counting endpoint, and the estimate stands in where there is none.
fn model_list_and_counting(api: Option<Api>) -> (bool, bool) {
    match api {
        Some(Api::AnthropicBedrock | Api::AnthropicVertex) => (false, false),
        Some(Api::OpenaiChat | Api::OpenaiResponses) => (true, false),
        Some(Api::AnthropicMessages | Api::GeminiGenerateContent) | None => (true, true),
    }
}

fn flag(f: &CompatFlag) -> String {
    match serde_json::to_value(f) {
        Ok(Value::String(s)) => s,
        Ok(Value::Object(o)) => o
            .into_iter()
            .map(|(k, v)| format!("{k}={}", v.as_str().unwrap_or_default()))
            .collect::<Vec<_>>()
            .join(","),
        _ => String::new(),
    }
}

fn yes(b: bool) -> &'static str {
    if b {
        "yes"
    } else {
        "no"
    }
}

/// The whole page. Rows come out in the order given.
pub fn render(rows: &[Row]) -> String {
    let mut out = String::from(
        "<!-- Generated by crates/aibus-testkit/tests/capability_matrix.rs from the presets and the catalog. Do not edit; see below. -->\n\
         # Capability matrix\n\n\
         This page is generated. I wrote a test that builds every preset's adapter, reads what it reports and the compat flags the preset names, counts the rows of its catalog file, and writes the table below. The same test fails when this file is not what it would write, so the matrix cannot drift from the code. To refresh it after changing a preset, an adapter or the catalog, run `AIBUS_WRITE_CAPABILITIES=1 cargo test -p aibus-testkit --test capability_matrix` (in a container) and commit the diff.\n\n\
         The capability columns are the provider's default for a model its table says nothing about; a catalog row can override any of them for one model (`docs/PROVIDERS.md`, \"What a model can do\"). `Auth` lists the `auth` forms the preset accepts. `Model list` is whether the adapter can ask the server for its models, and `Count tokens` whether it can count before a request (otherwise the estimate is used).\n\n\
         | Preset | API | Auth | Tools | Parallel tools | Thinking | Effort | Images | Prompt cache | Logprobs | Model list | Count tokens | Catalog rows | Compat flags |\n\
         |---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n",
    );
    for r in rows {
        let (list, count) = model_list_and_counting(r.def.api);
        let compat: Vec<String> = r.def.compat_flags().iter().map(flag).collect();
        out.push_str(&format!(
            "| `{}` | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |\n",
            r.def.id,
            r.def.api.map_or("?", Api::as_str),
            auth_kinds(&r.def).join(", "),
            yes(r.caps.tools),
            yes(r.caps.parallel_tool_calls),
            yes(r.caps.thinking),
            yes(r.caps.effort),
            yes(r.caps.images),
            yes(r.caps.prompt_cache),
            yes(r.caps.logprobs),
            yes(list),
            yes(count),
            r.catalog_rows,
            if compat.is_empty() { "none".to_owned() } else { compat.join(", ") },
        ));
    }
    out
}
