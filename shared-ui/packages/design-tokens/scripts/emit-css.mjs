// Writes dist/tokens.css from the compiled token data: light on :root, dark under
// [data-theme="dark"], and dark again under prefers-color-scheme unless data-theme="light" is set.
import { mkdirSync, writeFileSync } from 'node:fs';
import { colorTokens, scaleTokens, varName } from '../dist/tokens.js';

const decls = (obj, pad) =>
  Object.entries(obj)
    .map(([k, val]) => `${pad}${varName(k)}: ${val};`)
    .join('\n');

const css = `/* generated by scripts/emit-css.mjs, do not edit */
:root {
  color-scheme: light dark;
${decls(scaleTokens, '  ')}
${decls(colorTokens.light, '  ')}
}
:root[data-theme='light'] { color-scheme: light; }
:root[data-theme='dark'] {
  color-scheme: dark;
${decls(colorTokens.dark, '  ')}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${decls(colorTokens.dark, '    ')}
  }
}
`;
mkdirSync(new URL('../dist/', import.meta.url), { recursive: true });
writeFileSync(new URL('../dist/tokens.css', import.meta.url), css);
